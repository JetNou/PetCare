export const RegisterForm = () => {
  const {
    register,
    handleSubmit,
    formState: { errors },
    setError,
  } = useForm<RegisterFormData>({
    resolver: zodResolver(registerSchema),
  });
  const navigate = useNavigate()
  const { isOpen, openModal, closeModal, modalRef } = useModal(false);

  const onSubmit = async (data: RegisterFormData) => {
    try {
      const { data: tokens } = await authApi.register({
        user_login: data.login,
        user_email: data.email,
        user_password: data.password,
        user_full_name: data.full_name
      });
      localStorage.setItem("refresh_token", tokens.refresh_token);
      navigate("/verify-email");
    } catch (e) {
      setError("root", { message: getApiErrorMessage(e) });
    }
  };

  return (
    <>
      <form onSubmit={handleSubmit(onSubmit)} className="flex flex-col gap-5">

        <Input
          label="Логни"
          placeholder="Введите Логин"
          {...register("login")}
          error={errors.login?.message}
        />
        <Input
          label="Полное имя"
          placeholder="Введите имя"
          {...register("full_name")}
          error={errors.full_name?.message}
        />
        <Input
          label="Email"
          placeholder="Введите Email"
          {...register("email")}
          error={errors.email?.message}
        />

        <InputPassword
          label="Пароль"
          placeholder="Введите пароль"
          {...register("password")}
          error={errors.password?.message}
        />
        <InputPassword
          label="Подтверждение пароля"
          placeholder="Введите пароль повторно"
          {...register("confirm_password")}
          error={errors.confirm_password?.message}
        />

        <div className="flex items-start gap-x-2">
          <input
            id="rules_agree"
            type="checkbox"
            className="mt-0.5 h-5 w-5 shrink-0 cursor-pointer"
            {...register("agreement")}
          />
          <label htmlFor="rules_agree" className="text-sm text-brand-slate-alt leading-tight cursor-pointer">
            Я согласен(а) на обработку персональных данных в соответствии с{" "}
            <button
              type="button"
              onClick={(e) => {
                e.preventDefault();
                e.stopPropagation();
                openModal();
              }}
              className="inline font-semibold text-brand-primary underline transition-colors hover:text-orange-600"
            >
              политикой конфиденциальности
            </button>
          </label>
        </div>
        {errors.agreement && <p className="text-sm text-red-500">{errors.agreement.message}</p>}
        {errors.root && <p className="text-red-500 text-sm">{errors.root.message}</p>}

        <Button intent="primary" size="full">Зарегистрироваться</Button>
      </form>

      {isOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 p-4">
          <div
            ref={modalRef}
            className="flex max-h-[90vh] w-full max-w-4xl flex-col overflow-hidden rounded-3xl bg-white shadow-2xl"
          >
            <div className="flex items-start justify-between border-b border-brand-wood/20 px-5 py-4 sm:px-6">
              <div>
                <h2 className="text-xl font-extrabold text-brand-slate-alt sm:text-2xl">
                  Политика конфиденциальности
                </h2>
                <p className="mt-1 text-sm text-brand-slate">
                  веб-приложения «Система учета домашних животных PetCare»
                </p>
              </div>

              <button
                type="button"
                onClick={closeModal}
                className="ml-4 text-2xl leading-none text-brand-slate transition-colors hover:text-brand-primary"
                aria-label="Закрыть модальное окно"
              >
                ×
              </button>
            </div>

            <div className="overflow-y-auto px-5 py-4 sm:px-6 sm:py-5">
              <div className="whitespace-pre-line text-sm leading-6 text-brand-slate-alt">
                {privacyPolicyText}
              </div>
            </div>

            <div className="border-t border-brand-wood/20 px-5 py-4 sm:px-6">
              <Button type="button" intent="primary" onClick={closeModal}>
                Закрыть
              </Button>
            </div>
          </div>
        </div>
      )}
    </>
  )
}